/**
 * Puts our arms next to the competitor's published runs in one table.
 *
 *   node packages/agent/experiment/webvoyager/report.mjs [--out RESULTS.md]
 *
 * Reads results/webvoyager-*.json (ours) and baselines/webvoyager-*.json (lumen's own
 * published runs of lumen / stagehand / browser-use). Rows for runs whose task set is
 * not the 25-task set are labelled, never silently averaged in.
 *
 * NOT FOR PUBLICATION — part of the private packages/agent workspace.
 * @module agent/experiment/webvoyager/report
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { LUMEN_25 } from './dataset.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const args = process.argv.slice(2)
const outFlag = args.indexOf('--out')
const OUT = outFlag >= 0 ? args[outFlag + 1] : null

const read = (dir) => {
  let files = []
  try { files = readdirSync(join(HERE, dir)).filter((f) => f.endsWith('.json') && f.startsWith('webvoyager-')) } catch { return [] }
  return files.map((f) => ({ file: `${dir}/${f}`, ...JSON.parse(readFileSync(join(HERE, dir, f), 'utf-8')) }))
}

const runs = [...read('baselines'), ...read('results')]
if (!runs.length) { console.error('no runs found'); process.exit(1) }

const pct = (n) => (n * 100).toFixed(0) + '%'
const num = (n) => (n == null ? '—' : n.toLocaleString('en-US'))
const isFull25 = (r) => r.total === 25 && r.results.every((x) => LUMEN_25.includes(x.id))

// pass@1 is recoverable for every run, ours or theirs: a result recorded with trial > 1
// means trial 1 was judged FAIL. Headline numbers here are pass@3-with-judge-feedback;
// pass@1 is what a single unaided attempt achieves.
const pass1of = (r) => (r.passed1 != null ? r.passed1 : r.results.filter((x) => x.judgePass && x.trial === 1).length)

const rows = runs.map((r) => ({
  file: r.file,
  who: r.framework,
  set: isFull25(r) ? 'WV-25' : `subset(${r.total})`,
  model: r.model,
  judge: r.judgeModel,
  pass: `${r.passed}/${r.total} (${pct(r.passRate)})`,
  pass1: `${pass1of(r)}/${r.total} (${pct(pass1of(r) / r.total)})`,
  steps: r.avgSteps,
  tokens: num(r.avgTokens || null),
  secs: (r.avgDurationMs / 1000).toFixed(1),
  usd: r.usdAllTrials != null ? '$' + r.usdAllTrials : '—',
  ts: r.timestamp,
})).sort((a, b) => (a.set === b.set ? a.who.localeCompare(b.who) : a.set.localeCompare(b.set)))

const head = ['run', 'task set', 'model', 'judge', 'pass@3', 'pass@1', 'avg steps', 'avg tokens', 'avg s', 'spend']
const body = rows.map((r) => [r.who, r.set, r.model, r.judge, r.pass, r.pass1, r.steps, r.tokens, r.secs, r.usd])
const md = [
  '| ' + head.join(' | ') + ' |',
  '|' + head.map(() => '---').join('|') + '|',
  ...body.map((c) => '| ' + c.join(' | ') + ' |'),
].join('\n')

// Per-task pass/fail matrix over the 25-task set — where the arms actually differ.
const full = runs.filter(isFull25)
let matrix = ''
if (full.length > 1) {
  const cols = full.map((r) => r.framework)
  matrix = '\n\n### Per-task\n\n| task | ' + cols.join(' | ') + ' |\n|' + ['---', ...cols.map(() => '---')].join('|') + '|\n' +
    LUMEN_25.map((id) => {
      const cells = full.map((r) => {
        const t = r.results.find((x) => x.id === id)
        return t ? (t.judgePass ? `✅${t.trial > 1 ? ' t' + t.trial : ''}` : '❌') : '—'
      })
      return `| ${id} | ${cells.join(' | ')} |`
    }).join('\n')
}

const ours = runs.filter((r) => r.file.startsWith('results/'))
const note = ours.length
  ? ''
  : '\n> **Sin corridas propias todavía.** La tabla son solo los baselines publicados por el\n> competidor. Para agregar filas nuestras: `node run.mjs --arms oracle,pixels`.\n'

const text = `# WebVoyager-25 — results\n\nGenerated by \`report.mjs\` on ${new Date().toISOString().slice(0, 10)}.\nBaseline rows are the competitor's OWN published numbers (\`baselines/\`), not our re-runs.\n${note}\n${md}${matrix}\n`
if (OUT) { writeFileSync(join(HERE, OUT), text); console.log('wrote ' + OUT) } else console.log(text)
